package com.clamatiradores.declaracaohab.dto;

public class EventoRow {

	private String local;
	private String dataevento;
	private String treinoCompeticao;

	public String getLocal() {
		return local;
	}

	public void setLocal(String local) {
		this.local = local;
	}

	public String getDataevento() {
		return dataevento;
	}

	public void setDataevento(String dataevento) {
		this.dataevento = dataevento;
	}

	public String getTreinoCompeticao() {
		return treinoCompeticao;
	}

	public void setTreinoCompeticao(String treinoCompeticao) {
		this.treinoCompeticao = treinoCompeticao;
	}

}
